from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


def generate_payslip(employee, salary, salary_month):
    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )

    styles = getSampleStyleSheet()
    content = []

    content.append(Paragraph(
        "EMPLOYEE PAYSLIP",
        styles["Title"]
    ))
    content.append(Spacer(1, 8 * mm))

    details = [
        ["Employee Name", str(employee.get("name", ""))],
        ["Employee ID", str(employee.get("employee_id", ""))],
        ["Department", str(employee.get("department", ""))],
        ["Designation", str(employee.get("designation", ""))],
        ["Salary Month", str(salary_month)],
    ]

    details_table = Table(details, colWidths=[45 * mm, 110 * mm])
    details_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E0E7FF")),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#312E81")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))

    content.append(details_table)
    content.append(Spacer(1, 10 * mm))

    salary_rows = [
        ["Salary Component", "Amount (INR)"],
        ["Basic Salary", f'{salary["basic_salary"]:,.2f}'],
        ["Allowances", f'{salary["allowances"]:,.2f}'],
        ["Overtime", f'{salary["overtime"]:,.2f}'],
        ["Gross Salary", f'{salary["gross_salary"]:,.2f}'],
        ["Deductions", f'{salary["deductions"]:,.2f}'],
        ["NET SALARY", f'{salary["net_salary"]:,.2f}'],
    ]

    salary_table = Table(
        salary_rows,
        colWidths=[100 * mm, 55 * mm],
        repeatRows=1,
    )

    salary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4338CA")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("PADDING", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 4), (-1, 4), colors.HexColor("#D1FAE5")),
        ("BACKGROUND", (0, 6), (-1, 6), colors.HexColor("#CCFBF1")),
        ("FONTNAME", (0, 6), (-1, 6), "Helvetica-Bold"),
    ]))

    content.append(salary_table)
    content.append(Spacer(1, 10 * mm))
    content.append(Paragraph(
        "This payslip was generated by the Employee Payroll Management System.",
        styles["Normal"],
    ))

    document.build(content)
    buffer.seek(0)
    return buffer.getvalue()
